defmodule MediaServiceElxWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :media_service_elx
  import Plug.Conn

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_media_service_elx_key",
    signing_salt: "0d+s7eqc",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :media_service_elx,
    gzip: not code_reloading?,
    only: MediaServiceElxWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :media_service_elx
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library(),
    length: 50_000_000 #50mb

  plug Plug.MethodOverride
  plug Plug.Head
  plug :cors
  plug Plug.Session, @session_options
  plug MediaServiceElxWeb.Router

  defp cors(conn, _opts) do
    origin = get_req_header(conn, "origin") |> List.first()

    conn =
      if origin && origin in allowed_origins() do
        conn
        |> put_resp_header("access-control-allow-origin", origin)
        |> put_resp_header("access-control-allow-methods", "GET,POST,PUT,DELETE,OPTIONS")
        |> put_resp_header("access-control-allow-headers", "Authorization,Content-Type")
      else
        conn
      end

    if conn.method == "OPTIONS" do
      conn
      |> send_resp(204, "")
      |> halt()
    else
      conn
    end
  end

  defp allowed_origins do
    System.get_env("CORS_ALLOWED_ORIGINS", "http://localhost:23738")
    |> String.split(",", trim: true)
    |> Enum.map(&String.trim/1)
  end
end
