CREATE TABLE IF NOT EXISTS Chat (
    chat_id  UUID  PRIMARY KEY,
    title    VARCHAR(50)
);
CREATE TABLE IF NOT EXISTS chat_item (
    chat_item_id  UUID   PRIMARY KEY,
    chat_id       UUID   NOT NULL REFERENCES Chat(chat_id) ON DELETE CASCADE,
    protobuf      BYTEA  -- protobuf-encoded payload text & userId
);
CREATE TABLE IF NOT EXISTS allowed_users (
    allowed_user_id  UUID  PRIMARY KEY,
    chat_id          UUID  NOT NULL REFERENCES Chat(chat_id) ON DELETE CASCADE,
    user_id          UUID  NOT NULL,
    UNIQUE (chat_id, user_id)
